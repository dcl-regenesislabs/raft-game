// Losslessly trim transparent padding for the native main action only.
// Original inventory art is never modified. Run after changing item artwork.
const fs = require('node:fs')
const path = require('node:path')
const { PNG } = require('pngjs')
const root = path.resolve(__dirname, '..')
const sources = new Set([
  ...[...fs.readFileSync(path.join(root, 'src/ui/items.ts'), 'utf8').matchAll(/'((?:images\/)[^']+\.png)'/g)].map(m => m[1]),
  'images/hud/hands.png', 'images/hud/eraser.png'
])
const mapping = {}
for (const source of sources) {
  const input = PNG.sync.read(fs.readFileSync(path.join(root, source)))
  let left = input.width, top = input.height, right = -1, bottom = -1
  for (let y = 0; y < input.height; y++) for (let x = 0; x < input.width; x++) {
    if (input.data[(y * input.width + x) * 4 + 3] === 0) continue
    left = Math.min(left, x); top = Math.min(top, y)
    right = Math.max(right, x); bottom = Math.max(bottom, y)
  }
  if (right < left) continue
  const width = right - left + 1, height = bottom - top + 1
  const padding = Math.max(1, Math.ceil(Math.max(width, height) * 0.02))
  const side = Math.max(width, height) + 2 * padding
  // Keep artwork that already fills its canvas at its original scale.
  if (side >= Math.max(input.width, input.height)) continue
  const output = new PNG({ width: side, height: side })
  const dx = Math.floor((side - width) / 2), dy = Math.floor((side - height) / 2)
  PNG.bitblt(input, output, left, top, width, height, dx, dy)
  const destination = 'images/hud/main-action/' + source.replace(/^images\//, '').replaceAll('/', '-')
  fs.mkdirSync(path.dirname(path.join(root, destination)), { recursive: true })
  fs.writeFileSync(path.join(root, destination), PNG.sync.write(output))
  mapping[source] = destination
}
fs.writeFileSync(path.join(root, 'src/ui/mainActionIcons.ts'),
  '// Generated by scripts/build-main-action-icons.cjs. Inventory textures stay unchanged.\n' +
  'const MAIN_ACTION_ICONS: Record<string, string> = ' + JSON.stringify(mapping, null, 2) + '\n\n' +
  'export const MAIN_ACTION_ICON_ASSETS = Object.values(MAIN_ACTION_ICONS)\n\n' +
  'export function getMainActionIcon(source: string): string {\n  return MAIN_ACTION_ICONS[source] ?? source\n}\n')
console.log(`Prepared ${Object.keys(mapping).length} main-action icons without altering artwork pixels`)
